//*******Checking that vle8 leaves the tail (elements >= vl) undisturbed******//
// The destination is filled with a sentinel (0xee) over a 16-element window,
// then a different pattern (0x5a) is loaded into another register so that any
// stale data left inside the VLSU is recognizable. The partial load runs with
// tu/mu and vl ending in the middle of a 64-bit word: elements [vl, 16) must
// still hold 0xee afterwards.
//   0xee   -> correct (tail untouched)
//   0x5a   -> tail written with stale VLSU data
//   INP1[] -> tail written with memory data past vl

// vl = 1: tail starts at byte 1 of the first word
void TEST_CASE7(void) {
  volatile uint8_t INP1[] = {0x00, 0x9f, 0xe4, 0x19, 0x20, 0x8f, 0x2e, 0x05,
                             0xe0, 0xf9, 0xaa, 0x71, 0xf0, 0xc3, 0x94, 0xbb};
  VSET(16, e8, m1);
  VLOAD_8(v1, 0xee, 0xee, 0xee, 0xee, 0xee, 0xee, 0xee, 0xee,
              0xee, 0xee, 0xee, 0xee, 0xee, 0xee, 0xee, 0xee);
  VLOAD_8(v2, 0x5a, 0x5a, 0x5a, 0x5a, 0x5a, 0x5a, 0x5a, 0x5a,
              0x5a, 0x5a, 0x5a, 0x5a, 0x5a, 0x5a, 0x5a, 0x5a);

  VSET_TU(1, e8, m1);
  asm volatile("vle8.v v1, (%0)" ::"r"(INP1) : "memory");

  VSET(16, e8, m1);
  VCMP_U8(7, v1, 0x00, 0xee, 0xee, 0xee, 0xee, 0xee, 0xee, 0xee,
                 0xee, 0xee, 0xee, 0xee, 0xee, 0xee, 0xee, 0xee);
}

